#!/usr/bin/env node
/**
 * Writes THIRD_PARTY_NOTICES.md: every production dependency DASH ships (name, version, license, source), read from
 * the installed packages. Electron itself (and the Chromium inside it) ship their own notices in the app folder
 * (LICENSE.electron.txt, LICENSES.chromium.html).
 *
 *   node scripts/gen-third-party.mjs
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tree = JSON.parse(
  execFileSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['ls', '--omit=dev', '--all', '--json', '--long', '--workspace=apps/desktop'], {
    cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, shell: process.platform === 'win32',
  }),
);

const seen = new Map();
(function walk(deps) {
  for (const [name, info] of Object.entries(deps ?? {})) {
    if (name.startsWith('@dash/')) { walk(info.dependencies); continue; } // this repository's own packages
    if (!info.version) continue; // optional peer that is not installed
    const key = `${name}@${info.version}`;
    if (!seen.has(key)) {
      let lic = info.license;
      if (!lic && info.path) {
        try { lic = JSON.parse(fs.readFileSync(path.join(info.path, 'package.json'), 'utf8')).license; } catch { /* ignore */ }
      }
      if (lic && typeof lic === 'object') lic = lic.type;
      const repo = (info.repository?.url ?? info.homepage ?? '').replace(/^git\+/, '').replace(/\.git$/, '');
      seen.set(key, { name, version: info.version, license: lic || 'UNKNOWN', repo });
    }
    walk(info.dependencies);
  }
})(tree.dependencies);

const rows = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const counts = {};
for (const r of rows) counts[r.license] = (counts[r.license] ?? 0) + 1;

const md = [
  '# Third-party notices',
  '',
  'DASH is source-available and free to use (see `LICENSE`). It includes the following third-party packages, each under its',
  'own license. Generated by `node scripts/gen-third-party.mjs` from the installed production dependencies.',
  '',
  'Electron and the Chromium it embeds are separate works with their own notices (`LICENSE.electron.txt` and',
  '`LICENSES.chromium.html` inside the installed app folder).',
  '',
  `**${rows.length} packages.** By license: ${Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} (${v})`).join(', ')}.`,
  '',
  '| Package | Version | License | Source |',
  '|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.repo || ''} |`),
  '',
].join('\n');
fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), md);
console.log(`[DASH] Wrote THIRD_PARTY_NOTICES.md (${rows.length} packages)`);
const odd = rows.filter((r) => r.license === 'UNKNOWN' || /GPL|AGPL|SSPL/i.test(r.license));
if (odd.length) console.log('[DASH] Review these licenses:', odd.map((r) => `${r.name}@${r.version} (${r.license})`).join(', '));
